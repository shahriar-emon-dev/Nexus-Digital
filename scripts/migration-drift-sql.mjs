#!/usr/bin/env node
/**
 * Emits a read-only SQL query that compares the migrations in this repository
 * against `public.schema_migrations` in a live database.
 *
 *   node scripts/migration-drift-sql.mjs | psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f -
 *
 * Zero rows is a pass.
 *
 * WHY IT IS GENERATED RATHER THAN CHECKED IN. The comparison needs the list of
 * expected migrations, and a checked-in list is a second copy of the directory
 * listing — one that goes stale the first time someone adds a migration and
 * forgets to update it. A stale expected-list reports "MISSING FROM DATABASE"
 * for a migration that ran fine, everyone learns the check cries wolf, and it
 * gets ignored. Reading the directory at run time means it cannot disagree with
 * the directory.
 *
 * `scripts/check-migrations.mjs` is the offline half: it proves the files are
 * internally consistent. This is the half that needs a connection, and it
 * answers a different question — has what is on disk actually been applied, and
 * has anything been applied that is not on disk?
 */

import { readdirSync } from "node:fs";
import { join } from "node:path";

const DIR = join(process.cwd(), "supabase/migrations");

const rows = readdirSync(DIR)
  .filter((n) => /^\d{4}_[a-z0-9_]+\.sql$/.test(n))
  .sort()
  .map((n) => {
    const [, version, name] = /^(\d{4})_([a-z0-9_]+)\.sql$/.exec(n);
    return `  ('${version}','${name}')`;
  });

if (rows.length === 0) {
  console.error("-- no migrations found in supabase/migrations");
  process.exit(1);
}

process.stdout.write(`-- Generated by scripts/migration-drift-sql.mjs from ${rows.length} migration files.
-- Read-only. Zero rows is a pass.
with expected (version, name) as (values
${rows.join(",\n")}
),
applied as (
  select version, name from public.schema_migrations
)
select
  coalesce(e.version, a.version) as version,
  case
    when a.version is null then 'MISSING FROM DATABASE - this migration has not been applied'
    when e.version is null then 'MISSING FROM REPOSITORY - applied by hand, never committed'
    else 'NAME MISMATCH - two different migrations share one number'
  end as problem,
  e.name as repository_name,
  a.name as database_name
from expected e
full outer join applied a on a.version = e.version
where a.version is null
   or e.version is null
   or a.name is distinct from e.name
order by 1;
`);
